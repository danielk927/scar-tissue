"""Results report (P1-14): eval score per arm and generation from app.generations, as a Markdown table and a PNG chart.

Run: uv run python -m scar_experiments.report [--database-url URL] [--out docs/RESULTS.md] [--png docs/results.png]

The score of an arm at generation g is the eval score of the model and prompt that are current after g: a promoted
candidate's eval_score, a rejected candidate's parent_eval_score. Generation 0 is the shared base score, and arm A
(frozen base) is generation 0 repeated. Re-running on the same data writes byte-identical files.
"""

import argparse
import os
from dataclasses import dataclass
from pathlib import Path
from statistics import fmean

import matplotlib
import psycopg
from dotenv import load_dotenv
from matplotlib.backends.backend_agg import FigureCanvasAgg
from matplotlib.figure import Figure
from matplotlib.lines import Line2D
from matplotlib.ticker import FuncFormatter, MaxNLocator
from scar_schemas.models import GenerationRecord, GenStatus

from . import REPO_ROOT

ARM_NAMES = {"A": "Frozen base", "B": "Failure memory", "C": "GEPA", "D": "Weight updates (ours)", "E": "D + C"}
# Fixed color per arm (validated as a categorical set for CVD separation); text never wears these.
ARM_COLORS = {"D": "#2a78d6", "C": "#eb6834", "B": "#1baf7a", "E": "#eda100", "A": "#e87ba4"}
SURFACE, INK, INK_2, MUTED, GRID, BASELINE = "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"


@dataclass(frozen=True)
class Cell:
    arm: str
    generation: int
    mean: float
    min: float
    max: float
    n: int


def load_records(conn: psycopg.Connection) -> list[GenerationRecord]:
    rows = conn.execute("SELECT body FROM app.generations ORDER BY arm, seed, generation").fetchall()
    return [GenerationRecord.model_validate(body) for (body,) in rows]


def base_score(records: list[GenerationRecord]) -> float:
    """The shared generation-0 score: generation-0 eval scores if recorded, else generation-1 parent scores."""
    found = {r.eval_score for r in records if r.generation == 0 and r.eval_score is not None}
    if not found:
        found = {r.parent_eval_score for r in records if r.generation == 1 and r.parent_eval_score is not None}
    if len(found) != 1:
        raise ValueError(f"expected one shared generation-0 eval score in app.generations, found {sorted(found)}")
    return found.pop()


def summarize(records: list[GenerationRecord]) -> tuple[list[Cell], int]:
    """Cells sorted by arm then generation, and the number of unfinished records left out."""
    base = base_score(records)
    series: dict[tuple[str, int], dict[int, float]] = {}
    unfinished = 0
    for r in records:
        if r.arm == "A" or r.generation == 0:
            continue
        if r.status == GenStatus.promoted:
            score = r.eval_score
        elif r.status == GenStatus.rejected:
            score = r.parent_eval_score
        else:
            score = None
        if score is None:
            unfinished += 1
            continue
        series.setdefault((r.arm, r.seed), {0: base})[r.generation] = score
    last = max((g for s in series.values() for g in s), default=0)
    series[("A", 0)] = dict.fromkeys(range(last + 1), base)

    cells = []
    for arm in sorted({arm for arm, _ in series}):
        lineages = [series[key] for key in sorted(series) if key[0] == arm]
        for g in sorted({g for s in lineages for g in s}):
            values = [s[g] for s in lineages if g in s]
            cells.append(Cell(arm, g, fmean(values), min(values), max(values), len(values)))
    return cells, unfinished


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render_markdown(cells: list[Cell], unfinished: int, png_link: str) -> str:
    lines = [
        "# Results",
        "",
        "<!-- Generated by `uv run python -m scar_experiments.report` from app.generations. Do not edit by hand. -->",
        "",
        "Eval success rate on `eval_v1` (tasks from held-out companies) of the model and prompt that are current"
        " after each generation.",
        "A promoted candidate counts with its own score; after a rejection the parent's score carries forward.",
        "Generation 0 is the shared base score, and arm A (frozen base) stays at it.",
        "Mean, min and max are over seeds; n is the number of seeds.",
        "",
        f"![Eval success rate by generation]({png_link})",
        "",
        "| Arm | Generation | Mean | Min | Max | n |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for c in cells:
        stats = " | ".join(_pct(x) for x in (c.mean, c.min, c.max))
        lines.append(f"| {c.arm} - {ARM_NAMES[c.arm]} | {c.generation} | {stats} | {c.n} |")
    if unfinished:
        lines += ["", f"Unfinished generation records left out (neither promoted nor rejected): {unfinished}."]
    return "\n".join(lines) + "\n"


def _end_label_positions(ends: list[float], gap: float, top: float) -> list[float]:
    """Label heights for line ends sorted ascending: at least `gap` apart, shifted down if they pass `top`."""
    placed: list[float] = []
    for y in ends:
        placed.append(max(y, placed[-1] + gap) if placed else y)
    shift = max(0.0, placed[-1] - top) if placed else 0.0
    return [y - shift for y in placed]


def write_chart(cells: list[Cell], path: Path) -> None:
    """Line of the mean per arm with a min-max band. A legend names every arm; arms that reach the last generation
    also get a direct end label (on a leader line when labels had to be spread apart)."""
    arms = sorted({c.arm for c in cells})
    last = max(c.generation for c in cells)
    lo, hi = 100 * min(c.min for c in cells), 100 * max(c.max for c in cells)
    pad = max(2.0, 0.15 * (hi - lo))
    ymin, ymax = max(0.0, lo - pad), min(100.0, hi + pad)

    with matplotlib.rc_context({"font.family": "DejaVu Sans", "font.size": 9}):
        fig = Figure(figsize=(8, 4.5), dpi=200, facecolor=SURFACE)
        FigureCanvasAgg(fig)
        ax = fig.add_axes((0.08, 0.12, 0.80, 0.64), facecolor=SURFACE)
        ends, keys = [], []
        for arm in arms:
            arm_cells = [c for c in cells if c.arm == arm]
            gens = [c.generation for c in arm_cells]
            color = ARM_COLORS[arm]
            ax.fill_between(
                gens,
                [100 * c.min for c in arm_cells],
                [100 * c.max for c in arm_cells],
                color=color,
                alpha=0.10,
                linewidth=0,
            )
            ax.plot(
                gens,
                [100 * c.mean for c in arm_cells],
                color=color,
                linewidth=1.5,
                marker="o",
                markersize=6,
                markeredgecolor=SURFACE,
                markeredgewidth=1.5,
                solid_capstyle="round",
                solid_joinstyle="round",
                zorder=3,
            )
            keys.append(Line2D([], [], color=color, linewidth=2.5, solid_capstyle="round"))
            if gens[-1] == last:
                ends.append((100 * arm_cells[-1].mean, arm))

        ends.sort()
        heights = _end_label_positions([y for y, _ in ends], gap=0.06 * (ymax - ymin), top=ymax)
        for (y, arm), label_y in zip(ends, heights, strict=True):
            ax.plot([last + 0.1, last + 0.22], [y, label_y], color=MUTED, linewidth=0.6, clip_on=False, zorder=2)
            ax.text(last + 0.26, label_y, f"{arm}  {y:.1f}%", color=INK_2, va="center", ha="left", fontsize=8.5)

        ax.set_xlim(-0.2, last + 0.2)
        ax.set_ylim(ymin, ymax)
        ax.xaxis.set_major_locator(MaxNLocator(integer=True))
        ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:.0f}%"))
        ax.grid(axis="y", color=GRID, linewidth=0.75)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color(BASELINE)
        ax.tick_params(colors=MUTED, labelcolor=MUTED, length=0, pad=6)
        ax.set_xlabel("Generation", color=INK_2, labelpad=6)
        fig.text(0.08, 0.93, "Eval success rate by generation", color=INK, fontsize=13, weight="bold")
        fig.text(
            0.08,
            0.875,
            "Held-out companies (eval_v1). Line: mean over seeds; band: min to max.",
            color=INK_2,
            fontsize=9,
        )
        fig.legend(
            keys,
            [f"{arm} - {ARM_NAMES[arm]}" for arm in arms],
            loc="upper left",
            bbox_to_anchor=(0.072, 0.85),
            ncol=len(arms),
            frameon=False,
            fontsize=8.5,
            handlelength=1.2,
            columnspacing=1.6,
            labelcolor=INK_2,
        )
        fig.savefig(path, format="png", facecolor=SURFACE, metadata={"Software": None})


def main(argv: list[str] | None = None) -> None:
    load_dotenv(REPO_ROOT / ".env")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--database-url", default=os.environ.get("DATABASE_URL", "postgresql://scar:scar@localhost:5432/scar")
    )
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "RESULTS.md")
    parser.add_argument("--png", type=Path, default=REPO_ROOT / "docs" / "results.png")
    args = parser.parse_args(argv)

    with psycopg.connect(args.database_url) as conn:
        records = load_records(conn)
    try:
        cells, unfinished = summarize(records)
    except ValueError as e:
        raise SystemExit(f"error: {e}") from e
    for path in (args.out, args.png):
        path.parent.mkdir(parents=True, exist_ok=True)
    png_link = Path(os.path.relpath(args.png.resolve(), args.out.resolve().parent)).as_posix()
    args.out.write_text(render_markdown(cells, unfinished, png_link))
    write_chart(cells, args.png)
    print(f"wrote {args.out} and {args.png}")


if __name__ == "__main__":
    main()
